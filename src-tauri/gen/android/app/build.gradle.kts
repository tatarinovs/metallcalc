        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    signingConfigs {
        create("release") {
            val keystorePropertiesFile = rootProject.file("keystore.properties")
            if (keystorePropertiesFile.exists()) {
                val properties = Properties().apply {
                    keystorePropertiesFile.inputStream().use { load(it) }
                }
                val storeFilePath = properties.getProperty("storeFile")
                val store = if (File(storeFilePath).isAbsolute) File(storeFilePath) else rootProject.file(storeFilePath)
                if (store.exists()) {
                    storeFile = store
                    storePassword = properties.getProperty("storePassword")
                    keyAlias = properties.getProperty("keyAlias")
                    keyPassword = properties.getProperty("keyPassword")
                }
            } else {
                val defaultKeystore = rootProject.file("release.keystore")
                if (defaultKeystore.exists()) {
                    storeFile = defaultKeystore
                    storePassword = System.getenv("KEYSTORE_PASSWORD") ?: "metallcalc"
                    keyAlias = System.getenv("KEY_ALIAS") ?: "metallcalc"
                    keyPassword = System.getenv("KEY_PASSWORD") ?: "metallcalc"
                }
            }
        }
    }
    buildTypes {
        getByName("debug") {
            applicationIdSuffix = ".debug"
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {
